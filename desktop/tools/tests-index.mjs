import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..', '..');
const walk = (p) => fs.statSync(path.join(root, p)).isDirectory() ? fs.readdirSync(path.join(root, p)).flatMap((n) => walk(path.posix.join(p, n))) : [p];
const files = walk('test').filter((f) => f.endsWith('_test.dart')).sort();
const call = /\b(group|test|testWidgets)\s*\(\s*(?:'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"|'''([\s\S]*?)'''|([A-Za-z_$][\w$.]*|\$\{))/g;
let out = '# ONSET Android test index\n\nGenerated by desktop/tools/tests-index.mjs. Every group and test call in test/, in source order, with its line. The Dart tests are the behavioural oracle: each is ported to Rust.\n';
let total = 0;
for (const f of files) {
  const src = fs.readFileSync(path.join(root, f), 'utf8');
  const lines = [];
  for (const m of src.matchAll(call)) {
    const line = src.slice(0, m.index).split('\n').length;
    const name = (m[2] ?? m[3] ?? m[4] ?? `<expression: ${m[5]}>`).replace(/\s+/g, ' ');
    lines.push(`- L${line} ${m[1]}: ${name}`);
    if (m[1] !== 'group') total++;
  }
  out += `\n## ${f}\n\n${lines.join('\n') || '- (no group/test calls)'}\n`;
}
const dest = path.join(root, 'desktop/SPEC/12-tests-index.md');
fs.writeFileSync(dest, out);
console.log(`TESTS INDEX OK ${files.length} files ${total} tests`);
